"""Build STATUS.md from the per-department status files.

Usage: python3 rollup.py          # writes STATUS.md next to this file
       python3 rollup.py --selftest
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
STATUSES = ("DONE", "BLOCKED", "TODO")


def parse(text):
    """Return (title, [(id, task, due, status, note)]) from one status file."""
    title = text.splitlines()[0].lstrip("# ").split(" — ")[0]
    rows = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and cells[3].strip("*").upper() in STATUSES:
            rows.append((*cells[:3], cells[3].strip("*").upper(), " | ".join(cells[4:])))
    return title, rows


def render(depts):
    out = ["# Plan execution status", "",
           "Generated by `rollup.py` from the department files in this folder.", "",
           "| Department | Done | Blocked | Todo | Total |", "|---|---|---|---|---|"]
    totals = dict.fromkeys(STATUSES, 0)
    for name, file, rows in depts:
        n = {s: sum(r[3] == s for r in rows) for s in STATUSES}
        for s in STATUSES:
            totals[s] += n[s]
        out.append(f"| [{name}]({file}) | {n['DONE']} | {n['BLOCKED']} | {n['TODO']} | {len(rows)} |")
    out.append(f"| **All** | **{totals['DONE']}** | **{totals['BLOCKED']}** | **{totals['TODO']}** | **{sum(totals.values())}** |")
    out += ["", "## Blocked tasks", "", "| ID | Task | Blocker |", "|---|---|---|"]
    for _, _, rows in depts:
        out += [f"| {r[0]} | {r[1]} | {r[4]} |" for r in rows if r[3] == "BLOCKED"]
    return "\n".join(out) + "\n"


def render_open(depts):
    """Blocked + todo tasks grouped by department, most-blocked first."""
    link = re.compile(r"\[([^\]]+)\]\([^)]+\)")
    n = lambda rows, s: sum(r[3] == s for r in rows)
    all_rows = [r for _, _, rows in depts for r in rows]
    out = ["# Open tasks by department", "",
           f"Blocked and to-do tasks from the 2026-2027 plans. Generated by `rollup.py`. "
           f"**{n(all_rows, 'BLOCKED')} blocked · {n(all_rows, 'TODO')} to do · {n(all_rows, 'DONE')} done.**", "",
           "Blocked = waiting on owner or another department. To do = scheduled for a later date.", ""]
    for name, file, rows in sorted(depts, key=lambda d: -n(d[2], "BLOCKED")):
        out += [f"## {name}", "",
                f"{n(rows, 'BLOCKED')} blocked · {n(rows, 'TODO')} to do · {n(rows, 'DONE')} done · [full status]({file})", ""]
        for status, head, col in (("BLOCKED", "Blocked", "Waiting on"), ("TODO", "To do", "Notes")):
            sel = [r for r in rows if r[3] == status]
            if sel:
                out += [f"### {head}", "", f"| ID | Task | Due | {col} |", "|---|---|---|---|"]
                out += [f"| {r[0]} | {r[1]} | {r[2]} | {link.sub(lambda m: m.group(1), r[4])} |" for r in sel]
                out.append("")
    return "\n".join(out)


def main():
    depts = []
    for f in sorted(HERE.glob("*.md")):
        if f.name in ("STATUS.md", "OPEN-TASKS.md"):
            continue
        name, rows = parse(f.read_text())
        depts.append((name, f.name, rows))
    (HERE / "STATUS.md").write_text(render(depts))
    (HERE / "OPEN-TASKS.md").write_text(render_open(depts))
    print(f"STATUS.md + OPEN-TASKS.md: {len(depts)} departments")


def selftest():
    sample = "# Ops — status\n| ID | Task | Due | Status | Out |\n|---|---|---|---|---|\n" \
             "| OPS-01 | SOP | 24 Oct | DONE | [x](a.md) |\n| OPS-02 | Carrier | 6 Nov | **BLOCKED** | owner: carrier |\n"
    name, rows = parse(sample)
    assert name == "Ops" and [r[3] for r in rows] == ["DONE", "BLOCKED"], rows
    md = render([(name, "ops.md", rows)])
    assert "| [Ops](ops.md) | 1 | 1 | 0 | 2 |" in md and "| OPS-02 | Carrier | owner: carrier |" in md, md
    op = render_open([(name, "ops.md", rows)])
    assert "| OPS-02 | Carrier | 6 Nov | owner: carrier |" in op and "OPS-01" not in op, op
    print("selftest ok")


if __name__ == "__main__":
    selftest() if "--selftest" in sys.argv else main()
